n = float(input("Digite um numero: "))
quadrado = n**2
cubo = n**3
raiz = n**0.5

print(f"{n}² = {quadrado}")
print(f"{n}³ = {cubo}")
print(f"Raiz quadrada de {n} = {raiz}")

base = float(input("Digite a base:")) #`input()` lê o que o usuário digita — vem como string (texto)
altura = float(input("Digite a altura:"))

area = (base * altura) / 2
print(f"A area do trinagulo é {area}")

